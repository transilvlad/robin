"""Disposable local-Docker fixtures. Never resolve the real suite's Compose inputs."""

import json
import os
from pathlib import Path
import secrets
import subprocess
import tempfile
import uuid


SUITE = Path(__file__).resolve().parents[1]


def run(*arguments, **kwargs):
    kwargs.setdefault("timeout", 180)
    return subprocess.run(arguments, check=True, text=True, capture_output=True, **kwargs).stdout


class DockerFixture:
    def __init__(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="robin-acceptance-")
        self.root = Path(self.temporary.name)
        self.project = "robin-acceptance-" + uuid.uuid4().hex[:12]
        self.password = secrets.token_hex(32)
        self.created = False
        self.config = {
            "name": self.project,
            "services": {},
            "networks": {"backend": {"internal": True}},
            "volumes": {},
        }
        self.command = ["docker", "compose", "--project-name", self.project,
                        "--project-directory", str(self.root),
                        "-f", str(self.root / "compose.json")]

    def postgres(self):
        scripts = self.root / "init"
        scripts.mkdir()
        (scripts / "00-schema.sql").write_text("""
CREATE ROLE robin_mta LOGIN;
CREATE ROLE robin_mailbox LOGIN;
CREATE ROLE robin_admin LOGIN;
CREATE TABLE users (id SERIAL PRIMARY KEY, email TEXT UNIQUE NOT NULL, password TEXT NOT NULL,
 uid INTEGER DEFAULT 5000, gid INTEGER DEFAULT 5000, home TEXT, maildir TEXT);
CREATE TABLE aliases (id SERIAL PRIMARY KEY, source TEXT NOT NULL, destination TEXT NOT NULL);
CREATE TABLE auto_aliases (id SERIAL PRIMARY KEY, source TEXT NOT NULL, destination TEXT NOT NULL);
INSERT INTO users (email,password) VALUES ('alice@example.test','not-a-login'),
 ('bob@example.test','not-a-login'), ('shared@example.test','not-a-login');
GRANT SELECT ON users, aliases, auto_aliases TO robin_mailbox, robin_mta;
""", encoding="utf-8")
        self.config["services"]["postgres"] = {
            "image": os.environ.get("ROBIN_TEST_POSTGRES_IMAGE", "postgres:18-alpine"),
            "environment": {"POSTGRES_PASSWORD": self.password, "POSTGRES_DB": "robin",
                            "POSTGRES_INITDB_ARGS": "--no-sync"},
            "volumes": [f"{scripts}:/docker-entrypoint-initdb.d:ro", "database:/var/lib/postgresql"],
            "networks": {"backend": {"aliases": ["postgres-backend"]}},
            "mem_limit": "256m", "cpus": 1, "pids_limit": 128,
            "healthcheck": {"test": ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U postgres -d robin"],
                            "interval": "1s", "timeout": "5s", "retries": 60},
        }
        self.config["volumes"]["database"] = {}

    def start(self):
        self.validate_isolation()
        (self.root / "compose.json").write_text(json.dumps(self.config), encoding="utf-8")
        self.created = True
        try:
            run(*self.command, "up", "-d", "--wait", "--wait-timeout", "120")
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
            logs = run(*self.command, "logs", "--no-color", "--tail", "80")
            raise RuntimeError(f"Isolated fixture failed:\n{error.stderr}\n{logs}") from error
        return self

    def validate_isolation(self):
        if not self.project.startswith("robin-acceptance-"):
            raise ValueError("Invalid fixture project")
        for definition in self.config["services"].values():
            if any(key in definition for key in ("container_name", "network_mode", "privileged")):
                raise ValueError("Global or privileged container configuration is forbidden")
            for mount in definition.get("volumes", []):
                source = mount.rsplit(":", 2)[0] if mount.endswith(":ro") else mount.rsplit(":", 1)[0]
                if source not in self.config["volumes"]:
                    if not Path(source).resolve().is_relative_to(self.root.resolve()):
                        raise ValueError(f"Fixture bind outside temporary root: {source}")
            for port in definition.get("ports", []):
                if not isinstance(port, dict) or port.get("host_ip") != "127.0.0.1" or "published" in port:
                    raise ValueError("Only dynamically allocated loopback ports are allowed")
        for section in ("networks", "volumes"):
            if any(value.get("name") or value.get("external") for value in self.config[section].values()):
                raise ValueError("Globally named or external fixture state is forbidden")

    def sql(self, sql):
        return run(*self.command, "exec", "-T", "postgres", "psql", "-X", "-U", "postgres",
                   "-d", "robin", "-v", "ON_ERROR_STOP=1", "-At", input=sql)

    def close(self):
        if self.created:
            # Only the standalone, random project generated by this instance is touched.
            try:
                run(*self.command, "down", "--volumes", "--timeout", "10")
            except subprocess.CalledProcessError as error:
                print("Fixture Compose cleanup failed; retrying exact project-labelled resources:", error.stderr)
                for resource, listing, removal in (
                    ("container", ["ps", "-aq"], ["rm", "--force"]),
                    ("volume", ["volume", "ls", "-q"], ["volume", "rm"]),
                    ("network", ["network", "ls", "-q"], ["network", "rm"]),
                ):
                    ids = run("docker", *listing, "--filter", f"label=com.docker.compose.project={self.project}").split()
                    for identity in ids:
                        record = json.loads(run("docker", resource, "inspect", identity))[0]
                        labels = record.get("Labels", record.get("Config", {}).get("Labels", {}))
                        if labels.get("com.docker.compose.project") != self.project:
                            raise ValueError("Fixture cleanup refused an unowned resource")
                        run("docker", *removal, identity)
        self.temporary.cleanup()

    def __enter__(self):
        return self

    def __exit__(self, error_type, *_):
        try:
            if error_type is not None and (self.root / "compose.json").is_file():
                print(run(*self.command, "logs", "--no-color", "--tail", "60"))
        finally:
            self.close()
